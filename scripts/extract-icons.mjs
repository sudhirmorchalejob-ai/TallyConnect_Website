// Copies the Flutter app's icon path data (lib/core/design/tc_icon_paths.dart)
// into src/demo/icons.ts so the website draws exactly the app's icons.
// Usage: node scripts/extract-icons.mjs <path-to-tc_icon_paths.dart>
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) {
  console.error('Pass the path to tc_icon_paths.dart');
  process.exit(1);
}
const dart = readFileSync(src, 'utf8');
const body = dart.slice(dart.indexOf('{'), dart.lastIndexOf('}'));
const re = /'(\w+)':\s*((?:'[^']*'\s*)+),/g;
const out = {};
for (const m of body.matchAll(re)) {
  out[m[1]] = [...m[2].matchAll(/'([^']*)'/g)].map((x) => x[1]).join('');
}
const lines = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`);
writeFileSync(
  new URL('../src/demo/icons.ts', import.meta.url),
  `// Generated by scripts/extract-icons.mjs from the Tally Connect app's\n// tc_icon_paths.dart — 24×24 stroke icons (fill none, round caps).\nexport const ICONS = {\n${lines.join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`,
);
console.log(`Wrote ${lines.length} icons`);
